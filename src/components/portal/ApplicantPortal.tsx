import React from 'react';
import { jsPDF } from 'jspdf';
import { Download, FileText, CheckCircle2, Clock3, ArrowRight, BadgeCheck } from 'lucide-react';
import { AdmissionApplication, User } from '../../types';

interface ApplicantPortalProps {
  user: User;
  admissions: AdmissionApplication[];
  onNavigate: (view: string) => void;
}

const money = (value: number) => `₦${value.toLocaleString()}`;

const buildApplicantSummaryPdf = (application: AdmissionApplication) => {
  const pdf = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = pdf.internal.pageSize.getWidth();

  pdf.setFillColor(6, 78, 59);
  pdf.rect(0, 0, pageWidth, 80, 'F');
  pdf.setTextColor(255, 255, 255);
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(18);
  pdf.text('PECULIAR COLLEGE DOMA', 40, 42);
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(10);
  pdf.text('Candidate Admission Summary', 40, 62);

  pdf.setTextColor(15, 23, 42);
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(12);
  pdf.text('Applicant Details', 40, 110);
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(10);
  const lines = [
    `Name: ${application.firstName} ${application.middleName || ''} ${application.lastName}`,
    `Reference No: ${application.id}`,
    `Class Applying: ${application.classApplying} (${application.arm})`,
    `Status: ${application.status}`,
    `Submission Date: ${application.submissionDate}`,
    `Parent / Guardian: ${application.parentFullName}`,
    `Phone: ${application.parentPhone}`,
  ];
  lines.forEach((line, idx) => pdf.text(line, 40, 132 + idx * 18));

  pdf.setFont('helvetica', 'bold');
  pdf.text('Guidelines', 40, 320);
  pdf.setFont('helvetica', 'normal');
  const guidelines = [
    '• Keep the application reference number safe for future updates.',
    '• Bring required documents to the screening/interview session.',
    '• Attend the admissions test and oral interview if invited.',
    '• The school will communicate dates by phone, WhatsApp or email.',
  ];
  guidelines.forEach((line, idx) => pdf.text(line, 40, 340 + idx * 18));

  pdf.setFont('helvetica', 'bold');
  pdf.text('Fee Estimate', 320, 320);
  pdf.setFont('helvetica', 'normal');
  const feeRows = [
    `Application fee: ${money(5000)}`,
    `Screening / Exam fee: ${money(15000)}`,
    `Tuition / Class fee: ${money(application.arm === 'NURSERY' ? 35000 : application.arm === 'PRIMARY' ? 42000 : 55000)}`,
    `Development levy: ${money(application.arm === 'NURSERY' ? 4500 : application.arm === 'PRIMARY' ? 6000 : 8500)}`,
    `Sports levy: ${money(application.arm === 'SECONDARY' ? 6500 : 3500)}`,
    `Uniform fee: ${money(application.arm === 'SECONDARY' ? 12000 : 8000)}`,
    `Estimated total: ${money(application.arm === 'NURSERY' ? 70000 : application.arm === 'PRIMARY' ? 82000 : 104000)}`,
  ];
  feeRows.forEach((line, idx) => pdf.text(line, 320, 340 + idx * 18));

  pdf.setDrawColor(202, 138, 4);
  pdf.setLineWidth(1);
  pdf.line(40, 610, 555, 610);
  pdf.setFont('helvetica', 'italic');
  pdf.text('Generated by Peculiar College Doma Admissions Office', 40, 630);

  pdf.save(`applicant-summary-${application.id}.pdf`);
};

export const ApplicantPortal: React.FC<ApplicantPortalProps> = ({ user, admissions, onNavigate }) => {
  const myApplications = admissions.filter((app) => {
    const phoneMatch = user.phone && app.parentPhone.replace(/\s+/g, '') === user.phone.replace(/\s+/g, '');
    const emailMatch = !!user.email && !!app.parentEmail && app.parentEmail.toLowerCase() === user.email.toLowerCase();
    const nameMatch = !!app.parentFullName && user.name && app.parentFullName.toLowerCase().includes(user.name.toLowerCase());
    return phoneMatch || emailMatch || nameMatch || app.parentFullName === user.name;
  });

  const latestApplication = myApplications[0] || null;

  const downloadLatestSummary = () => {
    if (!latestApplication) return;
    buildApplicantSummaryPdf(latestApplication);
  };

  return (
    <div className="space-y-6 py-8">
      <section className="max-w-6xl mx-auto px-4 sm:px-6 lg:px-8">
        <div className="bg-gradient-to-r from-emerald-900 via-emerald-800 to-slate-900 text-white rounded-3xl p-8 shadow-lg border border-emerald-700">
          <div className="flex flex-col lg:flex-row lg:items-center lg:justify-between gap-6">
            <div>
              <p className="text-xs uppercase tracking-[0.2em] text-emerald-200">Applicant Portal</p>
              <h1 className="mt-2 text-3xl font-bold">Welcome, {user.name}</h1>
              <p className="mt-2 text-sm text-emerald-100 max-w-2xl">
                Manage your admission application, track your status, and download your official summary and offer letter when available.
              </p>
            </div>
            <button
              onClick={() => onNavigate('admissions')}
              className="inline-flex items-center justify-center gap-2 px-5 py-3 bg-amber-400 text-slate-950 font-bold rounded-xl shadow-sm hover:bg-amber-300"
            >
              Apply for Admission
              <ArrowRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      </section>

      <section className="max-w-6xl mx-auto px-4 sm:px-6 lg:px-8">
        {!latestApplication ? (
          <div className="bg-white border border-slate-200 rounded-3xl p-8 text-center shadow-sm">
            <div className="w-16 h-16 rounded-full bg-slate-100 flex items-center justify-center mx-auto mb-4">
              <FileText className="w-8 h-8 text-slate-500" />
            </div>
            <h2 className="text-2xl font-bold text-slate-900">No application submitted yet</h2>
            <p className="mt-2 text-sm text-slate-600">
              Start your child’s admission process by completing the online application form.
            </p>
            <button
              onClick={() => onNavigate('admissions')}
              className="mt-5 inline-flex items-center gap-2 px-5 py-3 bg-emerald-800 hover:bg-emerald-700 text-white rounded-xl font-bold text-sm"
            >
              Open Application Form
              <ArrowRight className="w-4 h-4" />
            </button>
          </div>
        ) : (
          <div className="grid grid-cols-1 xl:grid-cols-[1.2fr_0.8fr] gap-6">
            <div className="bg-white border border-slate-200 rounded-3xl p-6 shadow-sm">
              <div className="flex items-center justify-between gap-3 flex-wrap">
                <div>
                  <p className="text-[10px] uppercase tracking-[0.2em] text-slate-500">Latest Application</p>
                  <h2 className="text-2xl font-bold text-slate-900 mt-1">
                    {latestApplication.firstName} {latestApplication.lastName}
                  </h2>
                </div>
                <span className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-emerald-100 text-emerald-800 text-xs font-bold">
                  {latestApplication.status === 'ACCEPTED' ? <BadgeCheck className="w-4 h-4" /> : latestApplication.status === 'SUBMITTED' ? <Clock3 className="w-4 h-4" /> : <CheckCircle2 className="w-4 h-4" />}
                  {latestApplication.status.replace('_', ' ')}
                </span>
              </div>

              <div className="mt-6 grid grid-cols-1 md:grid-cols-2 gap-4 text-sm text-slate-700">
                <div className="p-4 bg-slate-50 rounded-xl border border-slate-200">
                  <span className="text-[10px] uppercase tracking-[0.2em] text-slate-500 block">Reference</span>
                  <span className="font-bold text-slate-900 mt-2 block">{latestApplication.id}</span>
                </div>
                <div className="p-4 bg-slate-50 rounded-xl border border-slate-200">
                  <span className="text-[10px] uppercase tracking-[0.2em] text-slate-500 block">Class</span>
                  <span className="font-bold text-slate-900 mt-2 block">{latestApplication.classApplying} ({latestApplication.arm})</span>
                </div>
                <div className="p-4 bg-slate-50 rounded-xl border border-slate-200">
                  <span className="text-[10px] uppercase tracking-[0.2em] text-slate-500 block">Parent</span>
                  <span className="font-bold text-slate-900 mt-2 block">{latestApplication.parentFullName}</span>
                </div>
                <div className="p-4 bg-slate-50 rounded-xl border border-slate-200">
                  <span className="text-[10px] uppercase tracking-[0.2em] text-slate-500 block">Submission</span>
                  <span className="font-bold text-slate-900 mt-2 block">{latestApplication.submissionDate}</span>
                </div>
              </div>

              <div className="mt-6 flex flex-wrap gap-3">
                <button
                  onClick={downloadLatestSummary}
                  className="inline-flex items-center gap-2 px-5 py-3 bg-slate-900 hover:bg-slate-800 text-white rounded-xl font-bold text-xs"
                >
                  <Download className="w-4 h-4" />
                  Download Summary PDF
                </button>
                {latestApplication.status === 'ACCEPTED' && (
                  <button
                    onClick={() => {
                      const letter = new jsPDF({ unit: 'pt', format: 'a4' });
                      letter.setFillColor(6, 78, 59);
                      letter.rect(0, 0, letter.internal.pageSize.getWidth(), 80, 'F');
                      letter.setTextColor(255, 255, 255);
                      letter.setFont('helvetica', 'bold');
                      letter.setFontSize(18);
                      letter.text('PECULIAR COLLEGE DOMA', 40, 42);
                      letter.setTextColor(15, 23, 42);
                      letter.setFontSize(12);
                      letter.text('Official Admission Letter', 40, 120);
                      letter.setFont('helvetica', 'normal');
                      letter.setFontSize(11);
                      const lines = [
                        `Dear ${latestApplication.parentFullName},`,
                        '',
                        `We are pleased to confirm that ${latestApplication.firstName} ${latestApplication.lastName} has been accepted for admission into ${latestApplication.classApplying} (${latestApplication.arm}).`,
                        'The school looks forward to welcoming the candidate for registration and orientation.',
                        'The expected school fee commitment is as follows:',
                        `• Tuition / Class Fee: ${money(latestApplication.arm === 'NURSERY' ? 35000 : latestApplication.arm === 'PRIMARY' ? 42000 : 55000)}`,
                        `• Development Levy: ${money(latestApplication.arm === 'NURSERY' ? 4500 : latestApplication.arm === 'PRIMARY' ? 6000 : 8500)}`,
                        `• Sports Levy: ${money(latestApplication.arm === 'SECONDARY' ? 6500 : 3500)}`,
                        `• Uniform Fee: ${money(latestApplication.arm === 'SECONDARY' ? 12000 : 8000)}`,
                        `• Total Estimated Fees: ${money(latestApplication.arm === 'NURSERY' ? 70000 : latestApplication.arm === 'PRIMARY' ? 82000 : 104000)}`,
                        '',
                        'Congratulations on this achievement.',
                        '',
                        'Mrs. R. A. Adams',
                        'Principal',
                        'Peculiar College Doma',
                      ];
                      const wrapped = lines.map((line) => line.length > 80 ? line.split(/(.{1,80})/).filter(Boolean) : [line]);
                      let y = 150;
                      wrapped.forEach((group) => {
                        group.forEach((entry) => {
                          letter.text(entry, 40, y);
                          y += 18;
                        });
                      });
                      letter.save(`admission-letter-${latestApplication.id}.pdf`);
                    }}
                    className="inline-flex items-center gap-2 px-5 py-3 bg-emerald-800 hover:bg-emerald-700 text-white rounded-xl font-bold text-xs"
                  >
                    <Download className="w-4 h-4" />
                    Download Admission Letter PDF
                  </button>
                )}
              </div>
            </div>

            <div className="bg-amber-50 border border-amber-200 rounded-3xl p-6 shadow-sm">
              <h3 className="text-lg font-bold text-slate-900">Admission status checklist</h3>
              <div className="mt-5 space-y-4 text-sm text-slate-700">
                <div className="flex gap-3">
                  <CheckCircle2 className="w-5 h-5 text-emerald-600 mt-0.5" />
                  <div>
                    <p className="font-semibold text-slate-900">Application submitted</p>
                    <p>Your form has been received by the admissions office.</p>
                  </div>
                </div>
                <div className="flex gap-3">
                  <Clock3 className="w-5 h-5 text-amber-600 mt-0.5" />
                  <div>
                    <p className="font-semibold text-slate-900">Review in progress</p>
                    <p>The admissions team is checking your documents and entry requirements.</p>
                  </div>
                </div>
                <div className="flex gap-3">
                  <BadgeCheck className="w-5 h-5 text-emerald-600 mt-0.5" />
                  <div>
                    <p className="font-semibold text-slate-900">Final offer</p>
                    <p>The school will notify you once the candidate is accepted.</p>
                  </div>
                </div>
              </div>
            </div>
          </div>
        )}
      </section>
    </div>
  );
};
